async def test_every_response_forbids_caching(panel: AsyncClient) -> None:
    act_as(panel, Role.OPS_MANAGER)
    for path in ("/admin/telephony", "/admin/overview", f"/admin/calls/{uuid.uuid4()}"):
        response = await panel.get(path)
        assert "no-store" in response.headers["cache-control"], path
    # A route that sets its own words keeps them and gains the one that matters.
    response = await panel.get("/health/live")
    assert response.headers["cache-control"] == "no-store"


