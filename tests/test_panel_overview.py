async def test_test_calls_are_counted_apart_from_real_ones(
    panel: AsyncClient, calls: dict[str, Any], app_engine: Any
) -> None:
    act_as(panel, Role.OPS_MANAGER)
    response = await panel.get("/admin/overview?range=today")
    assert response.status_code == 200, response.text
    body = response.json()

    assert body["range"] == "today"
    assert body["calls"]["total"] == await _counted(app_engine, test=False)
    assert body["calls"]["testCalls"] == await _counted(app_engine, test=True)
    assert body["calls"]["testCalls"] >= 1
    assert body["calls"]["total"] >= 4
    assert body["calls"]["inbound"] + body["calls"]["outbound"] == body["calls"]["total"]
    assert body["calls"]["transferred"] >= 1
    # The finished calls add up: answered by the agent, handed over, or missed.
    ended = (
        body["calls"]["answeredByAgent"] + body["calls"]["transferred"] + body["calls"]["missed"]
    )
    assert ended <= body["calls"]["total"]
    assert body["live"]["capacity"] > 0


