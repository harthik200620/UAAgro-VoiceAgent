"""The Overview page and the control plane's security posture (§15.1, §17).

The overview is arithmetic over rows the media path writes, and the
arithmetic has rules: a call placed from the browser page is counted apart,
a centre manager's page is their centres' page, and "today" is the Indian
day. These tests write a few calls the way the voice worker would and check
the sums, because a tile that is quietly wrong is worse than one that is
missing.
"""

from __future__ import annotations

import uuid
from collections.abc import AsyncIterator
from datetime import UTC, datetime, timedelta
from typing import Any

import pytest
from httpx import AsyncClient
from sqlalchemy import text
from sqlalchemy.ext.asyncio import async_sessionmaker

from tests.panel_support import act_as
from uaagro_domain.enums import CallDirection, CallOutcome, CallStatus, Role, TelephonyProvider

pytestmark = pytest.mark.integration

_SEVERITY = {"high": 0, "medium": 1, "low": 2}


