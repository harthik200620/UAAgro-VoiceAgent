@pytest.fixture
async def calls(app_engine) -> AsyncIterator[dict[str, Any]]:  # type: ignore[no-untyped-def]
    """A morning's calls, written the way the voice worker writes them.

    Four real calls and one from the browser page: a resolved helpline call,
    a hand-over nobody picked up, a call the agent did not understand, an
    outbound offer that was accepted, and a simulator run with a summary.
    """
    from uaagro_db.models import Call

    maker = async_sessionmaker(app_engine, expire_on_commit=False)
    started = datetime.now(UTC) - timedelta(seconds=30)
    rows: dict[str, Any] = {}

    async with maker() as session:
        await session.execute(text("SELECT set_config('app.role','ops_manager',true)"))
        org = await session.scalar(text("SELECT id FROM organizations LIMIT 1"))
        centre = await session.scalar(text("SELECT id FROM centres ORDER BY code LIMIT 1"))
        other_centre = await session.scalar(
            text("SELECT id FROM centres ORDER BY code DESC LIMIT 1")
        )

        def call(name: str, **fields: Any) -> None:
            row = Call(
                organization_id=org,
                call_ref=f"OVW-{uuid.uuid4().hex[:8].upper()}",
                started_at=started,
                answered_at=started,
                ended_at=started + timedelta(seconds=20),
                duration_seconds=20,
                status=CallStatus.COMPLETED,
                language_final="hi-IN",
                **fields,
            )
            session.add(row)
            rows[name] = row

        call(
            "resolved",
            direction=CallDirection.INBOUND,
            provider=TelephonyProvider.EXOTEL,
            centre_id=centre,
            outcome=CallOutcome.RESOLVED,
            latency_stats={"first_reply_ms": 900},
            intents=["price_enquiry"],
        )
        call(
            "handover",
            direction=CallDirection.INBOUND,
            provider=TelephonyProvider.EXOTEL,
            centre_id=centre,
            outcome=CallOutcome.TRANSFERRED,
            was_transferred=True,
            transfer_completed=False,
            latency_stats={"first_reply_ms": 1500},
            intents=["talk_to_human"],
        )
        call(
            "lost",
            direction=CallDirection.INBOUND,
            provider=TelephonyProvider.EXOTEL,
            centre_id=other_centre,
            outcome=CallOutcome.CALLER_HUNG_UP,
            latency_stats={"first_reply_ms": 700},
            intents=["unknown", "unknown"],
        )
        call(
            "offer",
            direction=CallDirection.OUTBOUND,
            provider=TelephonyProvider.EXOTEL,
            centre_id=centre,
            outcome=CallOutcome.OFFER_ACCEPTED,
            latency_stats={"first_reply_ms": 600},
            intents=["price_enquiry"],
        )
        call(
            "test",
            direction=CallDirection.INBOUND,
            provider=TelephonyProvider.SIMULATOR,
            centre_id=centre,
            outcome=CallOutcome.RESOLVED,
            latency_stats={"first_reply_ms": 400},
            summary_hi="किसान ने डीएपी का रेट पूछा।",
        )
        # The ids are generated by the database, so they exist after the flush.
        await session.flush()
        ids: dict[str, uuid.UUID] = {name: row.id for name, row in rows.items()}
        await session.commit()

    yield {"ids": ids, "centre": centre, "other_centre": other_centre}

    async with maker() as session:
        await session.execute(text("SELECT set_config('app.role','ops_manager',true)"))
        await session.execute(
            text("DELETE FROM calls WHERE id = ANY(:ids)"), {"ids": list(ids.values())}
        )
        await session.commit()


async def _counted(app_engine, *, test: bool) -> int:  # type: ignore[no-untyped-def]
    """What the database says today holds, for the overview to agree with."""
    from api.routers.panel_overview import window_for

    window = window_for("today")
    async with app_engine.connect() as connection:
        await connection.execute(text("SELECT set_config('app.role','ops_manager',true)"))
        return int(
            await connection.scalar(
                text(
                    "SELECT count(*) FROM calls WHERE started_at >= :start AND started_at < :end "
                    "AND (provider = 'simulator') = :test"
                ),
                {"start": window.start, "end": window.end, "test": test},
            )
            or 0
        )


