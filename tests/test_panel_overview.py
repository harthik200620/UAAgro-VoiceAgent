async def test_outcomes_speed_and_questions_come_from_the_calls(
    panel: AsyncClient, calls: dict[str, Any]
) -> None:
    act_as(panel, Role.OPS_MANAGER)
    body = (await panel.get("/admin/overview")).json()

    outcomes = {row["key"]: row for row in body["outcomes"]}
    assert outcomes["resolved"]["label"] == "Resolved"
    assert outcomes["offer_accepted"]["count"] >= 1
    counts = [row["count"] for row in body["outcomes"]]
    assert counts == sorted(counts, reverse=True)

    assert body["speed"]["firstReplyP50Ms"] is not None
    assert body["speed"]["firstReplyP95Ms"] >= body["speed"]["firstReplyP50Ms"]

    questions = {row["intent"]: row for row in body["topQuestions"]}
    assert questions["price_enquiry"]["count"] >= 2
    assert questions["price_enquiry"]["label"] == "What is the price?"
    # Not a question: a call the agent did not understand.
    assert "unknown" not in questions
    assert len(body["topQuestions"]) <= 8


async def test_by_hour_is_the_indian_day_and_adds_up(
    panel: AsyncClient, calls: dict[str, Any]
) -> None:
    act_as(panel, Role.OPS_MANAGER)
    today = (await panel.get("/admin/overview?range=today")).json()
    assert len(today["byHour"]) == 24
    assert today["byHour"][0]["hour"] == "00:00"
    assert today["byHour"][23]["hour"] == "23:00"
    assert sum(r["inbound"] + r["outbound"] for r in today["byHour"]) == today["calls"]["total"]

    week = (await panel.get("/admin/overview?range=7d")).json()
    assert len(week["byHour"]) == 7
    assert week["byHour"][-1]["hour"].split(" ")[0] in {
        "Mon",
        "Tue",
        "Wed",
        "Thu",
        "Fri",
        "Sat",
        "Sun",
    }
    assert week["calls"]["total"] >= today["calls"]["total"]

    month = (await panel.get("/admin/overview?range=30d")).json()
    assert len(month["byHour"]) == 30
    assert month["from"] <= week["from"] <= today["from"]


async def test_attention_names_the_handover_and_the_call_nobody_understood(
    panel: AsyncClient, calls: dict[str, Any]
) -> None:
    act_as(panel, Role.OPS_MANAGER)
    body = (await panel.get("/admin/overview")).json()
    items = body["attention"]
    assert len(items) <= 12
    ranks = [_SEVERITY[item["severity"]] for item in items]
    assert ranks == sorted(ranks), "most urgent first"

    by_kind = {item["kind"]: item for item in items}
    handover = by_kind["transfer_failed"]
    assert handover["severity"] == "high"
    assert handover["href"] == f"/calls/{calls['ids']['handover']}"
    assert handover["count"] >= 1

    lost = by_kind["unanswered"]
    assert lost["href"] == f"/calls/{calls['ids']['lost']}"
    assert lost["count"] >= 1
    for item in items:
        assert item["title"], item
        assert isinstance(item["count"], int)


